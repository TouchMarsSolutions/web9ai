import { describe, expect, it } from "vitest";
import { isSafeCssValue } from "./css-value.mjs";

describe("isSafeCssValue", () => {
	it.each([
		["color", "#E6E6FA"],
		["color", "rgb(10, 20, 30)"],
		["background", "linear-gradient(135deg, rgba(148, 0, 211, 0.9), #4B0082)"],
		["background", "radial-gradient(circle, rgba(255,255,255,.4), transparent)"],
		["padding", "100px 20px"],
		["margin", "0 auto"],
		["box-shadow", "0 2px 8px rgba(0,0,0,0.2)"],
		["color", "#1e3e3e"],
		["box-shadow", "0 2px 8px rgb(255, 255, 255)"],
		["margin", "1em 0"],
		["padding", "0.5rem 1rem"],
		["line-height", "1.6"],
		["font-size", "18px"],
		["font-size", "large"],
		["border-radius", "50%"],
		["background", "linear-gradient(90deg, #fff 0%, #000 100%)"],
		["width", "100%"],
	])("accepts %s: %s", (prop, value) => expect(isSafeCssValue(prop, value)).toBe(true));
	it.each([
		["background", "red\nurl(//evil.example/t.gif)"],
		["background", "url(https://evil.example/t.gif)"],
		["background", "image-set('//evil.example/t.gif' 1x)"],
		["background", "-webkit-image-set(x 1x)"],
		["background", "cross-fade(a, b)"],
		["background", "src(x)"],
		["background", "element(#foo)"],
		["background", "paint(foo)"],
		["width", "attr(data-w px)"],
		["color", "var(--x, red)"],
		["background", "//evil.example/t.gif"],
		["box-shadow", "0 0 0 9999px red"],
		["box-shadow", "0 0 0 100vmax #000"],
		["width", "100vw"],
		["margin", "-9999px 0 0 -9999px"],
		["margin", "-1px"],
		["padding", "99999px"],
		["font-size", "9999px"],
		["color", "red /* x */"],
		["color", "expression(alert(1))"],
		["width", "calc((100% - 1px)"],
		["color", ""],
		["box-shadow", "0 0 0 1e4px red"],
		["box-shadow", "0 0 0 1E4px red"],
		["box-shadow", "0 0 0 1.5e3px red"],
		["box-shadow", "0 0 0 64in red"],
		["box-shadow", "0 0 0 64em red"],
		["box-shadow", "0 0 0 calc(40px + 40px) red"],
		["box-shadow", "0 0 0 calc(64px / .01) red"],
		["margin", "calc(0px - 200px)"],
		["margin", "calc(0px - 1e4px) 0 0 calc(0px - 1e4px)"],
		["margin", "min(0px, 0px - 250px)"],
		["width", "1e5px"],
		["width", "10cm"],
		["width", "calc(100% - 20px)"],
		["max-width", "min(100%, 600px)"],
		["padding", "256in"],
		["padding", "5pt"],
		["font-size", "1e4px"],
		["font-size", "1.2em"],
		["font-size", "200%"],
		["font-size", "2rem"],
		["line-height", "2000"],
		["line-height", "100"],
	])("rejects %s: %j", (prop, value) => expect(isSafeCssValue(prop, value)).toBe(false));
});
