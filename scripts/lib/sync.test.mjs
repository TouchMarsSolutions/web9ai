import { describe, expect, it } from "vitest";
import { canonical, firstDifference, upsertEntry, upsertMenu } from "./sync.mjs";

/** In-memory stand-in for the MCP content and menu tools, with the measured behaviour. */
function fakeCms() {
	const rows = [];
	const calls = [];
	let n = 0;
	const find = (collection, id, locale) => rows.find((r) => r.collection === collection && (r.id === id || r.slug === id) && (!locale || r.locale === locale));
	const view = (r) => ({ item: { ...r, data: structuredClone(r.data) }, _rev: `rev${r.rev}` });
	let menu = { name: "primary", items: [{ label: "Blog", type: "custom", customUrl: "/posts", target: null }] };
	const tools = {
		content_get: ({ collection, id, locale }) => {
			const r = find(collection, id, locale);
			if (!r) throw new Error(`content_get: NOT_FOUND: no ${collection} item ${id}`);
			return view(r);
		},
		content_create: ({ collection, slug, locale, status, data, translationOf }) => {
			const id = `01ID${++n}`;
			const group = translationOf ? find(collection, translationOf).translationGroup : id;
			const live = status === "published";
			rows.push({ id, collection, slug, locale, status, data, translationGroup: group, draftRevisionId: null, liveRevisionId: live ? `live${id}` : null, publishedAt: live ? "2026-01-01T00:00:00.000Z" : null, rev: 1 });
			return view(rows.at(-1));
		},
		content_update: ({ collection, id, data, _rev }) => {
			const r = find(collection, id);
			if (_rev !== `rev${r.rev}`) throw new Error("content_update: CONFLICT");
			if (r.locked) throw new Error("content_update: ENTRY_LOCKED");
			Object.assign(r, { data: { ...r.data, ...data }, draftRevisionId: `d${r.rev}`, rev: r.rev + 1 });
			return view(r);
		},
		content_publish: ({ collection, id, _rev }) => {
			const r = find(collection, id);
			if (_rev !== `rev${r.rev}`) throw new Error("content_publish: CONFLICT");
			if (r.locked) throw new Error("content_publish: ENTRY_LOCKED");
			Object.assign(r, { status: "published", draftRevisionId: null, liveRevisionId: `live${r.id}`, publishedAt: r.publishedAt ?? "2026-01-02T00:00:00.000Z", rev: r.rev + 1 });
			return view(r);
		},
		// The admin's unpublish: status draft, no live revision, published_at kept, a draft copy of the live version.
		content_unpublish: ({ collection, id, _rev }) => {
			const r = find(collection, id);
			if (_rev !== `rev${r.rev}`) throw new Error("content_unpublish: CONFLICT");
			Object.assign(r, { status: "draft", liveRevisionId: null, draftRevisionId: r.draftRevisionId ?? `copy${r.rev}`, rev: r.rev + 1 });
			return view(r);
		},
		menu_get: () => structuredClone(menu),
		menu_set_items: ({ items }) => {
			menu = { name: "primary", items: items.map((i) => ({ label: i.label, type: i.type, customUrl: i.customUrl, target: i.target ?? null })) };
			return menu;
		},
	};
	const callTool = async (name, args) => {
		calls.push(name);
		return tools[name](args);
	};
	return { rows, calls, callTool, writes: () => calls.filter((c) => !/_get$/.test(c)) };
}

const doc = (data, extra = {}) => ({ collection: "docs", slug: "intro", locale: "en", status: "published", data, ...extra });

describe("upsertEntry", () => {
	it("creates a missing entry as published, then leaves it alone", async () => {
		const cms = fakeCms();
		expect(await upsertEntry(cms.callTool, doc({ title: "Intro", body: [] }))).toMatchObject({ action: "created", id: "01ID1" });
		expect(await upsertEntry(cms.callTool, doc({ title: "Intro", body: [] }))).toMatchObject({ action: "unchanged", id: "01ID1" });
		expect(cms.writes()).toEqual(["content_create"]);
	});
	it("updates and publishes a changed entry, comparing only the wanted fields", async () => {
		const cms = fakeCms();
		await upsertEntry(cms.callTool, doc({ title: "Intro", body: [{ a: 1 }] }));
		cms.rows[0].data.search_text = "generated by the hook";
		const res = await upsertEntry(cms.callTool, doc({ title: "Intro", body: [{ a: 2 }] }), { overwrite: true });
		expect(res).toMatchObject({ action: "updated", diff: expect.stringContaining("body[0].a") });
		expect(cms.rows[0]).toMatchObject({ status: "published", draftRevisionId: null, data: { body: [{ a: 2 }] } });
		expect(cms.writes()).toEqual(["content_create", "content_update", "content_publish"]);
	});
	it("publishes a draft left behind by an interrupted run", async () => {
		const cms = fakeCms();
		await upsertEntry(cms.callTool, doc({ title: "Intro" }));
		cms.rows[0].draftRevisionId = "pending";
		expect(await upsertEntry(cms.callTool, doc({ title: "Intro" }))).toMatchObject({ action: "published" });
		expect(cms.writes().at(-1)).toBe("content_publish");
	});
	it("links a translation on create and checks the link afterwards", async () => {
		const cms = fakeCms();
		const en = await upsertEntry(cms.callTool, doc({ title: "Intro" }));
		const zh = { ...doc({ title: "入门" }), locale: "zh-CN", translationOf: en.id, translationGroup: en.translationGroup };
		expect(await upsertEntry(cms.callTool, zh)).toMatchObject({ action: "created", translationGroup: en.translationGroup });
		expect(await upsertEntry(cms.callTool, zh)).toMatchObject({ action: "unchanged" });
		cms.rows[1].translationGroup = "someone-else";
		await expect(upsertEntry(cms.callTool, zh)).rejects.toThrow(/not linked to its en original/);
	});
	it("writes nothing in a dry run", async () => {
		const cms = fakeCms();
		expect(await upsertEntry(cms.callTool, doc({ title: "Intro" }), { dryRun: true })).toEqual({ action: "created", id: null });
		await upsertEntry(cms.callTool, doc({ title: "Intro" }));
		expect(await upsertEntry(cms.callTool, doc({ title: "Changed" }), { dryRun: true })).toMatchObject({ action: "updated" });
		expect(cms.writes()).toEqual(["content_create"]);
	});
	it("stops on a lock and on errors other than not-found", async () => {
		const cms = fakeCms();
		await upsertEntry(cms.callTool, doc({ title: "Intro" }));
		cms.rows[0].locked = true;
		await expect(upsertEntry(cms.callTool, doc({ title: "Changed" }), { overwrite: true })).rejects.toThrow(/ENTRY_LOCKED.*never override/);
		const broken = async () => {
			throw new Error("MCP HTTP 401: unauthorized");
		};
		await expect(upsertEntry(broken, doc({ title: "Intro" }))).rejects.toThrow(/401/);
	});
	it("never replaces a published entry that differs unless overwrite is set", async () => {
		const cms = fakeCms();
		await upsertEntry(cms.callTool, doc({ title: "Intro", body: [{ a: 1 }] }));
		const edited = doc({ title: "Intro", body: [{ a: 2 }] });
		await expect(upsertEntry(cms.callTool, edited)).rejects.toThrow(/^\[WOULD_OVERWRITE\] docs\/intro \(en\): body\[0\]\.a: stored 1 \/ wanted 2/);
		expect(cms.writes()).toEqual(["content_create"]);
		expect(await upsertEntry(cms.callTool, edited, { dryRun: true })).toMatchObject({ action: "updated", diff: expect.stringContaining("body[0].a") });
		expect(await upsertEntry(cms.callTool, edited, { overwrite: true })).toMatchObject({ action: "updated" });
		expect(cms.writes()).toEqual(["content_create", "content_update", "content_publish"]);
		expect(await upsertEntry(cms.callTool, edited)).toMatchObject({ action: "unchanged" });
	});
	it("stops on a pending draft that differs from the migration, even with overwrite or in a dry run", async () => {
		const cms = fakeCms();
		const created = await upsertEntry(cms.callTool, doc({ title: "Intro", body: [{ a: 1 }] }));
		const { _rev } = await cms.callTool("content_get", { collection: "docs", id: created.id, locale: "en" });
		await cms.callTool("content_update", { collection: "docs", id: created.id, data: { body: [{ a: 9 }] }, _rev });
		const writesBefore = cms.writes().length;
		const wanted = doc({ title: "Intro", body: [{ a: 1 }] });
		await expect(upsertEntry(cms.callTool, wanted)).rejects.toThrow(/^\[PENDING_DRAFT\] docs\/intro \(en\): body\[0\]\.a: stored 9 \/ wanted 1/);
		await expect(upsertEntry(cms.callTool, wanted, { overwrite: true })).rejects.toThrow(/\[PENDING_DRAFT\]/);
		await expect(upsertEntry(cms.callTool, wanted, { dryRun: true })).rejects.toThrow(/\[PENDING_DRAFT\]/);
		expect(cms.writes().length).toBe(writesBefore);
		expect(cms.rows[0]).toMatchObject({ status: "published", data: { body: [{ a: 9 }] } });
	});
	it("publishes a pending draft that equals the migration", async () => {
		const cms = fakeCms();
		const created = await upsertEntry(cms.callTool, doc({ title: "Intro", body: [{ a: 1 }] }));
		const { _rev } = await cms.callTool("content_get", { collection: "docs", id: created.id, locale: "en" });
		await cms.callTool("content_update", { collection: "docs", id: created.id, data: { body: [{ a: 2 }] }, _rev });
		expect(await upsertEntry(cms.callTool, doc({ title: "Intro", body: [{ a: 2 }] }))).toMatchObject({ action: "published" });
		expect(cms.rows[0]).toMatchObject({ status: "published", draftRevisionId: null });
	});
	it("stops when the migration wants a draft but the entry is published", async () => {
		const cms = fakeCms();
		await upsertEntry(cms.callTool, doc({ title: "Intro" }));
		const draft = doc({ title: "Intro" }, { status: "draft" });
		await expect(upsertEntry(cms.callTool, draft)).rejects.toThrow(/^\[STATUS_MISMATCH\] docs\/intro \(en\)/);
		await expect(upsertEntry(cms.callTool, draft, { overwrite: true })).rejects.toThrow(/\[STATUS_MISMATCH\]/);
		expect(cms.writes()).toEqual(["content_create"]);
	});
	it("keeps a wanted draft a draft, replacing it only with overwrite and never publishing it", async () => {
		const cms = fakeCms();
		const draft = (text) => doc({ title: text }, { status: "draft" });
		await upsertEntry(cms.callTool, draft("One"));
		expect(await upsertEntry(cms.callTool, draft("One"))).toMatchObject({ action: "unchanged" });
		await expect(upsertEntry(cms.callTool, draft("Two"))).rejects.toThrow(/\[WOULD_OVERWRITE\]/);
		expect(await upsertEntry(cms.callTool, draft("Two"), { overwrite: true })).toMatchObject({ action: "updated" });
		expect(cms.writes()).toEqual(["content_create", "content_update"]);
		expect(cms.rows[0].status).toBe("draft");
		await expect(upsertEntry(cms.callTool, draft("Three"), { overwrite: true })).rejects.toThrow(/\[PENDING_DRAFT\]/);
	});
	it("never republishes an entry that was unpublished in the admin", async () => {
		const cms = fakeCms();
		const created = await upsertEntry(cms.callTool, doc({ title: "Intro" }));
		const { _rev } = await cms.callTool("content_get", { collection: "docs", id: created.id, locale: "en" });
		await cms.callTool("content_unpublish", { collection: "docs", id: created.id, _rev });
		const writesBefore = cms.writes().length;
		for (const options of [{}, { overwrite: true }, { dryRun: true }]) {
			await expect(upsertEntry(cms.callTool, doc({ title: "Intro" }), options)).rejects.toThrow(/^\[STATUS_MISMATCH\] docs\/intro \(en\)/);
		}
		expect(cms.writes().length).toBe(writesBefore);
		expect(cms.rows[0].status).toBe("draft");
	});
	it("never overwrites a draft-status entry that was saved since, whatever the status", async () => {
		const cms = fakeCms();
		const draft = (text) => doc({ title: text }, { status: "draft" });
		const created = await upsertEntry(cms.callTool, draft("One"));
		const { _rev } = await cms.callTool("content_get", { collection: "docs", id: created.id, locale: "en" });
		await cms.callTool("content_update", { collection: "docs", id: created.id, data: { title: "Edited by a human" }, _rev });
		const writesBefore = cms.writes().length;
		for (const options of [{}, { overwrite: true }, { dryRun: true }]) {
			await expect(upsertEntry(cms.callTool, draft("One"), options)).rejects.toThrow(/^\[PENDING_DRAFT\] docs\/intro \(en\): title: stored "Edited by a human" \/ wanted "One"/);
		}
		expect(cms.writes().length).toBe(writesBefore);
		// Wanted draft that already equals the stored draft stays unchanged (it carries a draft revision after any save).
		expect(await upsertEntry(cms.callTool, draft("Edited by a human"))).toMatchObject({ action: "unchanged" });
	});
	it("publishes the draft that a crashed create leaves behind, and nothing that merely looks like it", async () => {
		const leftover = async (mutate = () => {}) => {
			const cms = fakeCms();
			// content_create(status published) is create-as-draft then publish; a crash in between leaves this row.
			await cms.callTool("content_create", { collection: "docs", slug: "intro", locale: "en", status: "draft", data: { title: "Intro" } });
			mutate(cms.rows[0]);
			return cms;
		};
		const cms = await leftover();
		expect(await upsertEntry(cms.callTool, doc({ title: "Intro" }), { dryRun: true })).toMatchObject({ action: "published" });
		expect(await upsertEntry(cms.callTool, doc({ title: "Intro" }))).toMatchObject({ action: "published" });
		expect(cms.rows[0]).toMatchObject({ status: "published", draftRevisionId: null });
		// A draft that looks like a leftover but differs may be a person's (created in the admin, or saved then
		// discarded): never replaced, with overwrite or in a dry run.
		const stale = await leftover();
		const writesBefore = stale.writes().length;
		for (const options of [{}, { overwrite: true }, { dryRun: true }]) {
			await expect(upsertEntry(stale.callTool, doc({ title: "Changed" }), options)).rejects.toThrow(/^\[STATUS_MISMATCH\] docs\/intro \(en\)/);
		}
		expect(stale.writes().length).toBe(writesBefore);
		expect(stale.rows[0]).toMatchObject({ status: "draft", data: { title: "Intro" } });
		// Anything that has been published or saved before is somebody's decision, not a leftover.
		const wasPublished = await leftover((r) => (r.publishedAt = "2026-01-01T00:00:00.000Z"));
		const wasSaved = await leftover((r) => (r.draftRevisionId = "saved"));
		for (const other of [wasPublished, wasSaved]) {
			await expect(upsertEntry(other.callTool, doc({ title: "Intro" }))).rejects.toThrow(/\[STATUS_MISMATCH\]/);
			expect(other.rows[0].status).toBe("draft");
		}
	});
	it("stops when publishing hits a lock", async () => {
		const cms = fakeCms();
		await upsertEntry(cms.callTool, doc({ title: "Intro" }));
		cms.rows[0].draftRevisionId = "pending";
		cms.rows[0].locked = true;
		await expect(upsertEntry(cms.callTool, doc({ title: "Intro" }))).rejects.toThrow(/docs\/01ID1.*ENTRY_LOCKED.*never override/);
		expect(cms.rows[0].draftRevisionId).toBe("pending");
	});
	it("treats the real content_get not-found message as a missing entry, but not an HTTP 404", async () => {
		const calls = [];
		const real = async (name, args) => {
			calls.push(name);
			if (name === "content_get") throw new Error("content_get: [NOT_FOUND] Content item not found: intro");
			return { item: { id: "01REAL", translationGroup: "01REAL" }, _rev: "r1" };
		};
		expect(await upsertEntry(real, doc({ title: "Intro" }))).toMatchObject({ action: "created", id: "01REAL" });
		expect(calls).toEqual(["content_get", "content_create"]);
		const wrongUrl = async () => {
			throw new Error("MCP HTTP 404: Not Found");
		};
		await expect(upsertEntry(wrongUrl, doc({ title: "Intro" }))).rejects.toThrow(/HTTP 404/);
	});
	it("stops with the hook's message when a save is rejected, without retrying", async () => {
		const cms = fakeCms();
		let attempts = 0;
		const rejecting = async (name, args) => {
			if (name === "content_create") {
				attempts++;
				throw new Error("content_create: [SAVE_REJECTED] body[0]: htmlBlock is not allowed");
			}
			return cms.callTool(name, args);
		};
		await expect(upsertEntry(rejecting, doc({ title: "Intro" }))).rejects.toThrow(/SAVE_REJECTED.*htmlBlock/);
		expect(attempts).toBe(1);
	});
});

describe("upsertMenu", () => {
	const items = [
		{ label: "AI", type: "custom", customUrl: "/docs/intro" },
		{ label: "GitHub", type: "custom", customUrl: "https://github.com/TouchMarsSolutions/web9ai", target: "_blank" },
	];
	it("replaces the items once with overwrite, then reports unchanged", async () => {
		const cms = fakeCms();
		expect(await upsertMenu(cms.callTool, "primary", items, { overwrite: true })).toMatchObject({ action: "updated" });
		expect(await upsertMenu(cms.callTool, "primary", items)).toEqual({ action: "unchanged" });
		expect(cms.writes()).toEqual(["menu_set_items"]);
	});
	it("never replaces a different menu without overwrite, but a dry run reports the difference", async () => {
		const cms = fakeCms();
		await expect(upsertMenu(cms.callTool, "primary", items)).rejects.toThrow(/^\[WOULD_OVERWRITE\] menu\/primary: \[0\]\.label: stored "Blog" \/ wanted "AI"/);
		expect(await upsertMenu(cms.callTool, "primary", items, { dryRun: true })).toMatchObject({ action: "updated", diff: expect.stringContaining("[0].label") });
		expect(cms.writes()).toEqual([]);
	});
	it("treats a null target like no target", async () => {
		const cms = fakeCms();
		expect(await upsertMenu(cms.callTool, "primary", [{ label: "Blog", type: "custom", customUrl: "/posts" }])).toEqual({ action: "unchanged" });
	});
});

describe("canonical / firstDifference", () => {
	it("ignores key order and names the first differing path", () => {
		expect(canonical({ b: 1, a: [{ d: 1, c: 2 }] })).toBe(canonical({ a: [{ c: 2, d: 1 }], b: 1 }));
		expect(firstDifference({ a: [1, { b: 2 }] }, { a: [1, { b: 3 }] })).toMatch(/^a\[1\]\.b: stored 2 \/ wanted 3$/);
		expect(firstDifference({ a: 1 }, { a: 1 })).toBeNull();
	});
});
